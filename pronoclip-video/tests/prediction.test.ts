import { describe, it, expect } from 'vitest'
import { predictMatch, detectInputLevel, validateScore } from '../core/prediction'
import type { PredictionInput } from '../core/types'
import { HOME, AWAY, GOAL_TYPES_SET } from './fixtures'

const base = (over: Partial<PredictionInput> = {}): PredictionInput => ({
  home: HOME,
  away: AWAY,
  seed: 12345,
  ...over,
})

describe('detectInputLevel', () => {
  it('L0 quand rien n’est fourni', () => {
    expect(detectInputLevel(base())).toBe('L0')
  })
  it('L1 quand seul le score est fourni', () => {
    expect(detectInputLevel(base({ score: { home: 2, away: 1 } }))).toBe('L1')
  })
  it('L2 quand score + buteurs (sans types)', () => {
    expect(detectInputLevel(base({
      score: { home: 1, away: 0 },
      goals: [{ teamSide: 'home', playerName: 'Alonso' }],
    }))).toBe('L2')
  })
  it('L3 quand tout est fourni', () => {
    expect(detectInputLevel(base({
      score: { home: 1, away: 0 },
      goals: [{ teamSide: 'home', playerName: 'Alonso', goalType: 'goal_header' }],
    }))).toBe('L3')
  })
})

describe('L0 — pronostic auto', () => {
  it('produit un score plafonné à 2 buts/équipe', () => {
    for (let seed = 0; seed < 50; seed++) {
      const p = predictMatch(base({ seed }))
      expect(p.score.home).toBeLessThanOrEqual(2)
      expect(p.score.away).toBeLessThanOrEqual(2)
    }
  })
  it('buteurs issus de l’effectif, types valides, comptes cohérents', () => {
    const p = predictMatch(base())
    const roster = new Set([...HOME.players, ...AWAY.players].map(x => x.name))
    expect(p.goals).toHaveLength(p.score.home + p.score.away)
    for (const g of p.goals) {
      expect(roster.has(g.playerName)).toBe(true)
      expect(GOAL_TYPES_SET.has(g.goalType)).toBe(true)
    }
    expect(p.autoGenerated).toEqual({ score: true, scorers: true, goalTypes: true })
  })
  it('est déterministe pour une graine donnée', () => {
    expect(predictMatch(base({ seed: 999 }))).toEqual(predictMatch(base({ seed: 999 })))
  })
  it('respecte une contrainte de marché (victoire extérieure)', () => {
    const p = predictMatch(base({ seed: 7, market: { result: 'away' } }))
    expect(p.score.away).toBeGreaterThan(p.score.home)
  })
})

describe('L1 — score fourni sans buteurs', () => {
  it('respecte le score et ne prédit que le reste', () => {
    const p = predictMatch(base({ score: { home: 2, away: 1 } }))
    expect(p.score).toEqual({ home: 2, away: 1 })
    expect(p.goals).toHaveLength(3)
    expect(p.autoGenerated).toEqual({ score: false, scorers: true, goalTypes: true })
    // Ordre chronologique interleave : home, away, home.
    expect(p.goals.map(g => g.teamSide)).toEqual(['home', 'away', 'home'])
    expect(p.goals.map(g => g.matchOrder)).toEqual([1, 2, 3])
  })
  it('buteurs distincts quand l’effectif le permet (2 buts domicile)', () => {
    const p = predictMatch(base({ score: { home: 2, away: 0 } }))
    const homeScorers = p.goals.filter(g => g.teamSide === 'home').map(g => g.playerName)
    expect(new Set(homeScorers).size).toBe(2)
  })
})

describe('L2 — score + buteurs fournis', () => {
  it('ne réécrit jamais les buteurs fournis, ne prédit que les types', () => {
    const p = predictMatch(base({
      score: { home: 2, away: 1 },
      goals: [
        { teamSide: 'home', playerName: 'Aubert' },
        { teamSide: 'away', playerName: 'Blanc' },
        { teamSide: 'home', playerName: 'Amiot' },
      ],
    }))
    expect(p.goals.map(g => g.playerName)).toEqual(['Aubert', 'Blanc', 'Amiot'])
    expect(p.autoGenerated).toEqual({ score: false, scorers: false, goalTypes: true })
    for (const g of p.goals) expect(GOAL_TYPES_SET.has(g.goalType)).toBe(true)
  })
})

describe('L3 — tout fourni', () => {
  it('ne prédit rien et conserve valeurs + types', () => {
    const p = predictMatch(base({
      score: { home: 1, away: 1 },
      goals: [
        { teamSide: 'home', playerName: 'Alonso', goalType: 'goal_penalty' },
        { teamSide: 'away', playerName: 'Bardo', goalType: 'goal_header' },
      ],
    }))
    expect(p.autoGenerated).toEqual({ score: false, scorers: false, goalTypes: false })
    expect(p.goals.map(g => g.goalType)).toEqual(['goal_penalty', 'goal_header'])
  })
})

describe('cas limites de score', () => {
  it('0-0 → aucun but', () => {
    const p = predictMatch(base({ score: { home: 0, away: 0 } }))
    expect(p.goals).toHaveLength(0)
  })
  it('1-0', () => {
    const p = predictMatch(base({ score: { home: 1, away: 0 } }))
    expect(p.goals).toHaveLength(1)
    expect(p.goals[0].teamSide).toBe('home')
  })
  it('4-3 → 7 buts, ordre chronologique alterné', () => {
    const p = predictMatch(base({ score: { home: 4, away: 3 } }))
    expect(p.goals).toHaveLength(7)
    expect(p.goals.filter(g => g.teamSide === 'home')).toHaveLength(4)
    expect(p.goals.filter(g => g.teamSide === 'away')).toHaveLength(3)
    expect(p.goals.map(g => g.matchOrder)).toEqual([1, 2, 3, 4, 5, 6, 7])
  })
})

describe('plafonds de réalisme', () => {
  it('rejette > 5 buts/équipe', () => {
    expect(() => validateScore({ home: 6, away: 0 })).toThrow()
    expect(() => predictMatch(base({ score: { home: 6, away: 0 } }))).toThrow()
  })
  it('rejette > 7 buts au total', () => {
    expect(() => validateScore({ home: 5, away: 3 })).toThrow()
  })
  it('rejette une égalité en élimination directe', () => {
    expect(() => validateScore({ home: 1, away: 1 }, true)).toThrow()
  })
  it('rejette un score incompatible avec le marché', () => {
    expect(() => predictMatch(base({ score: { home: 0, away: 0 }, market: { result: 'home' } }))).toThrow()
  })
})
